#!/usr/bin/env python3
"""Regenerate the bundled LVGL CJK subsets from the characters the UI uses.

The subset fonts are easy to under-fill: add a label, forget the converter run,
and the panel shows an empty box while everything still compiles. Hand-kept
symbol lists drift for the same reason, so this script derives the set from the
sources with the same literal scanner `check_glyphs.py` uses, then re-runs the
converter and verifies the result.

Only the sizes that carry CJK are regenerated by default (16/20 px). The 24/40 px
fonts are ASCII-only (codes, digits, "6+1"), so they need no CJK pass.

Usage:
    python tools/gen_fonts.py            # regenerate 16 px and 20 px
    python tools/gen_fonts.py --check    # print the set without converting
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import check_glyphs as cg  # noqa: E402  (needs the path tweak above)

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets" / "fonts"
SOURCE_FONT = FONT_DIR / "NotoSansCJKsc-Regular.otf"
DEFAULT_SIZES = (16, 20)
ASCII_RANGE = "0x20-0x7E"


def collect_points(root: Path) -> set[int]:
    """Non-ASCII code points that application sources may draw on the panel."""
    points: set[int] = set()
    for path in cg.iter_files(root, ("main",), cg.SOURCE_SUFFIXES):
        text = path.read_text(encoding="utf-8")
        if cg.IGNORE_FILE_MARKER in text:
            continue
        for literal in cg.scan_source(text):
            points.update(point for point in literal.codepoints if point >= cg.ASCII_LIMIT)
    return points


def render(size: int, symbols: str) -> Path:
    out = FONT_DIR / f"lucky_font_{size}.c"
    # Windows resolves the launcher as npx.cmd; subprocess does not do that for us.
    npx = shutil.which("npx") or "npx.cmd"
    command = [
        npx, "--yes", "lv_font_conv@1.5.3",
        "--font", str(SOURCE_FONT),
        "--size", str(size),
        "--bpp", "4",
        "--format", "lvgl",
        "--no-compress",
        "--lv-font-name", f"lucky_font_{size}",
        "--lv-include", "lvgl.h",
        "--range", ASCII_RANGE,
        "--symbols", symbols,
        "--output", str(out),
    ]
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"lv_font_conv failed for {size}px:\n{result.stdout}{result.stderr}")
    return out


def verify(path: Path, expected: set[int]) -> int:
    """Return the number of code points the fresh font is missing."""
    points = cg.font_codepoints(path.read_text(encoding="utf-8"), path.name) or set()
    return len(expected - points)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sizes", nargs="+", type=int, default=list(DEFAULT_SIZES))
    parser.add_argument("--check", action="store_true", help="only list the glyph set")
    args = parser.parse_args(argv)

    points = collect_points(ROOT)
    if not points:
        sys.exit("no non-ASCII literals found; refusing to emit an empty font")
    symbols = "".join(chr(point) for point in sorted(points))
    print(f"glyph set: {len(points)} code point(s) -> {symbols}")
    if args.check:
        return 0

    for size in args.sizes:
        path = render(size, symbols)
        missing = verify(path, points)
        if missing:
            sys.exit(f"{path.name}: {missing} requested code point(s) still missing")
        print(f"{path.relative_to(ROOT).as_posix()}: {path.stat().st_size} B, all covered")
    return 0


if __name__ == "__main__":
    sys.exit(main())
