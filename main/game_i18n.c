bool game_i18n_language_valid(game_language_t language)
{
    return (unsigned)language < GAME_LANGUAGE_COUNT;
}

const char *game_i18n_get(game_language_t language, game_text_id_t text)
{
    if (!game_i18n_language_valid(language)) language = GAME_LANGUAGE_ZH_CN;
    if ((unsigned)text >= GAME_TEXT_COUNT) text = GAME_TEXT_UNKNOWN;
    const char *value = s_text[language][text];
    return value ? value : s_text[language][GAME_TEXT_UNKNOWN];
}
